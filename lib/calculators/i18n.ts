function translateLabel(value: string) {
  return labelPT[value] ?? value;
}

function translateField(field: CalculatorField): CalculatorField {
  return {
    ...field,
    label: translateLabel(field.label),
    placeholder: field.placeholder ? translateLabel(field.placeholder) : field.placeholder,
    helpText: field.helpText ? translateLabel(field.helpText) : field.helpText,
    options: field.options?.map((option) => ({
      ...option,
      label: translateLabel(option.label),
    })),
  };
}

export function localizeCalculator(config: CalculatorConfig, language: Language): CalculatorConfig {
  if (language === "en") return config;

  return {
    ...config,
    title: titlePT[config.title] ?? config.title,
    description: descriptionPT[config.description] ?? config.description,
    explanation: explanationPT[config.explanation] ?? config.explanation,
    fields: config.fields.map(translateField),
    formula: config.formula,
    notes: config.notes?.map(translateLabel),
    faq: config.faq?.map((item) => ({
      ...item,
      question: translateLabel(item.question),
      answer: translateLabel(item.answer),
    })),
    calculate: (inputs) => config.calculate(inputs).map((result) => ({
      ...result,
      label: translateLabel(result.label),
    })),
  };
}

export function getCategoryTranslation(category: string, language: Language) {
  if (language === "en") return null;
  return categoryPT[category] ?? null;
}
